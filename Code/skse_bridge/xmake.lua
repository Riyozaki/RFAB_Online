target("RFABCoopState")
    set_kind("shared")
    set_basename("RFAB_CoopState")
    set_group("Client")
    add_includedirs("../common")
    add_files("main.cpp")
    add_syslinks("kernel32")
    after_install(function(target)
        local plugins = path.join(target:installdir(), "Data", "SKSE", "Plugins")
        os.mkdir(plugins)
        os.cp(target:targetfile(), path.join(plugins, "RFAB_CoopState.dll"))
    end)
